"""Emit a pipeline sample-sheet fragment for downloaded external samples.

The output is a standalone, valid sample sheet in the same shape as
``configs/sample_metadata.yaml`` (a ``defaults:`` block + a ``samples:`` map),
written to ``configs/external/{dataset}_samples.yaml``. Point the mapping
stage at it via ``pipeline_config.yaml``'s ``configs.samples`` (as
``MarcantiaSample.yaml`` is used), or copy the entries into an existing sheet.

Runs belonging to one biological sample (multiple lanes / SRR per GSM) are
grouped, so ``fastq1``/``fastq2`` become the per-lane lists the mapping stage
already expects.
"""

from __future__ import annotations

import os
from collections import OrderedDict

import yaml

from .util import log


def _represent_ordereddict(dumper, data):
    """YAML representer keeping an OrderedDict's key order."""
    return dumper.represent_mapping("tag:yaml.org,2002:map", data.items())


yaml.add_representer(OrderedDict, _represent_ordereddict)


def build_sheet(sample_entries: dict, *, default_tech: str, sample_type: str,
                mapping_config: str = "default") -> OrderedDict:
    """Assemble the full sheet dict (defaults + samples)."""
    doc = OrderedDict()
    doc["defaults"] = OrderedDict([
        ("mapper", "alevin"),
        ("mapping_config", mapping_config),
        ("qc_filter", "default"),
        ("sample_type", sample_type),
        ("tech", default_tech),
    ])
    doc["samples"] = OrderedDict(sorted(sample_entries.items()))
    return doc


def sample_entry(*, fastq1: list[str], fastq2: list[str], batch: str,
                 tech: str | None, sample_type: str | None) -> OrderedDict:
    """One sample's block. Only per-sample overrides are written; anything equal
    to the sheet default is left to ``defaults:``.
    """
    entry = OrderedDict()
    entry["batch"] = batch
    if tech:
        entry["tech"] = tech
    if sample_type:
        entry["sample_type"] = sample_type
    entry["fastq1"] = fastq1
    entry["fastq2"] = fastq2
    return entry


def write_sheet(doc: OrderedDict, path: str) -> None:
    """Write a fetched dataset's sample sheet, with the schema modeline and a review header."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    header = (
        # Modeline on line 1 (repo convention). One extra '../' vs the top-level
        # sheets because generated sheets live in configs/external/.
        "# yaml-language-server: $schema=../schemas/sample_sheet.schema.json\n"
        "# Generated by fetch for externally-fetched data.\n"
        "# Standalone sample sheet: point pipeline_config.yaml's `configs.samples`\n"
        "# here, or copy entries into an existing sheet. REVIEW before mapping --\n"
        "# `tech` (10x chemistry) is inferred from R1 read length and may need a\n"
        "# matching entry in technology_config.yaml (e.g. 10xv2 is not defined there).\n"
    )
    with open(path, "w") as fh:
        fh.write(header)
        yaml.dump(doc, fh, default_flow_style=False, sort_keys=False, width=1000)
    log().info("[SHEET] wrote %s (%d samples)", path, len(doc["samples"]))
